const fmt = (n) => Number(n || 0).toLocaleString('en-US');

function Section({ title, tone, children }) {
  return (
    <section className="rf-section">
      <h4 className={`rf-bar is-${tone}`}>{title}</h4>
      {children}
    </section>
  );
}

/**
 * The monitoring report as tables (same numbers and sections as the printed
 * form). `data` comes from buildReportData().
 */
export default function ReportFormTables({ data, reportNumber }) {
  if (!data) return null;
  return (
    <div className="rf-tables">
      <Section title="Monitoring information" tone="green">
        <table className="rf-table rf-info">
          <tbody>
            <tr><th>Camera ID</th><td>{data.info.cameras || '—'}</td><th>Monitoring location</th><td>{data.info.location}</td></tr>
            <tr><th>Monitoring period</th><td>{data.info.period}</td><th>Date generated</th><td>{data.info.generatedAt}</td></tr>
            <tr><th>Generated by</th><td>{data.info.generatedBy}</td><th>Monitoring duration</th><td>{data.info.duration}</td></tr>
            <tr><th>Average confidence</th><td>{data.info.averageConfidence}</td><th>Report No.</th><td>{reportNumber || '—'}</td></tr>
          </tbody>
        </table>
      </Section>

      <Section title="Waste detection summary" tone="blue">
        <table className="rf-table rf-summary">
          <thead>
            <tr><th>Waste category</th><th>Classifications</th><th className="rf-num">Total</th></tr>
          </thead>
          <tbody>
            {data.summary.map((row) => (
              <tr key={row.category}>
                <td>{row.category}</td>
                <td className="rf-muted">{row.classifications.join(', ')}</td>
                <td className="rf-num"><b>{fmt(row.total)}</b></td>
              </tr>
            ))}
            <tr className="rf-total"><td colSpan={2}>Grand total</td><td className="rf-num">{fmt(data.grandTotal)}</td></tr>
          </tbody>
        </table>
      </Section>

      {/* Left: Waste classification. Right: Detection statistics over Detection summary by date. */}
      <div className="rf-pair">
        <Section title="Waste classification" tone="yellow">
          <table className="rf-table rf-classes">
            <thead>
              <tr><th>Waste classification</th><th>Category</th><th className="rf-num">Count</th></tr>
            </thead>
            <tbody>
              {data.classes.map((row) => (
                <tr key={row.name}>
                  <td>{row.name}</td>
                  <td className="rf-muted">{row.category}</td>
                  <td className="rf-num"><b>{fmt(row.count)}</b></td>
                </tr>
              ))}
            </tbody>
          </table>
        </Section>

        <Section title="Detection statistics" tone="rose">
          <table className="rf-table rf-stats">
            <thead>
              <tr><th>Description</th><th className="rf-num">Value</th></tr>
            </thead>
            <tbody>
              <tr><td>Records in this report</td><td className="rf-num"><b>{fmt(data.statistics.records)}</b></td></tr>
              <tr><td>Detection events</td><td className="rf-num"><b>{fmt(data.statistics.events)}</b></td></tr>
              <tr><td>Today&apos;s detections</td><td className="rf-num"><b>{fmt(data.statistics.today)}</b></td></tr>
              <tr><td>All-time detections</td><td className="rf-num"><b>{fmt(data.statistics.allTime)}</b></td></tr>
              <tr>
                <td title="Left the camera view; inferred, not proof of cleaning">No longer visible (inferred)</td>
                <td className="rf-num"><b>{fmt(data.statistics.notVisible)}</b></td>
              </tr>
              <tr>
                <td title="Confirmed on site by the Barangay Sanitary Inspector or an administrator">Cleaning verified</td>
                <td className="rf-num"><b>{fmt(data.statistics.verified)}</b></td>
              </tr>
            </tbody>
          </table>
        </Section>
        <Section title="Detection summary by date" tone="green">
          <div className="rf-scroll">
            <table className="rf-table">
              <thead>
                <tr>
                  <th>Date</th>
                  {data.categories.map((c) => <th key={c} className="rf-num">{c}</th>)}
                  <th className="rf-num">Total</th>
                </tr>
              </thead>
              <tbody>
                {data.dates.length === 0 ? (
                  <tr><td colSpan={data.categories.length + 2} className="rf-muted">No dated records in this report.</td></tr>
                ) : (
                  data.dates.map((row) => (
                    <tr key={row.date}>
                      <td>{row.date}</td>
                      {data.categories.map((c) => <td key={c} className="rf-num">{fmt(row.counts[c])}</td>)}
                      <td className="rf-num"><b>{fmt(row.total)}</b></td>
                    </tr>
                  ))
                )}
                <tr className="rf-total">
                  <td>Total</td>
                  {data.categories.map((c) => (
                    <td key={c} className="rf-num">{fmt(data.summary.find((s) => s.category === c)?.total)}</td>
                  ))}
                  <td className="rf-num">{fmt(data.grandTotal)}</td>
                </tr>
              </tbody>
            </table>
          </div>
        </Section>
      </div>

      <Section title="Observations" tone="gray">
        <p className="rf-text">{data.observations}</p>
      </Section>
      <Section title="Recommendations" tone="royal">
        <p className="rf-text">{data.recommendations}</p>
      </Section>
    </div>
  );
}
